-- 4a) Mandefa fangatahana (voafetra: contact/hafatra/taona, 5 miandry isaky ny contact)
create or replace function public.request_activation(
  p_name text, p_contact text, p_year integer, p_message text)
returns bigint
language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_contact text := btrim(coalesce(p_contact, ''));
begin
  if length(v_contact) < 3 or length(v_contact) > 120 then raise exception 'contact_invalid'; end if;
  if length(coalesce(p_name, '')) > 120 or length(coalesce(p_message, '')) > 1000 then raise exception 'too_long'; end if;
  if p_year is null or p_year < 2026 or p_year > 2100 then raise exception 'year_invalid'; end if;
  if (select count(*) from public.activation_requests
      where requester_contact = v_contact and status = 'pending') >= 5 then
    raise exception 'too_many_pending';
  end if;
  insert into public.activation_requests (requester_name, requester_contact, year, message, status)
  values (btrim(coalesce(p_name, '')), v_contact, p_year, btrim(coalesce(p_message, '')), 'pending')
  returning id into v_id;
  return v_id;
end $$;

-- 4b) Jerena ny valin'ny fangatahana (amin'ny contact ihany; code hita rehefa ekena)
create or replace function public.my_activation_requests(p_contact text)
returns table (id bigint, year integer, status text, code_issued text, admin_note text, created_at timestamptz)
language sql security definer set search_path = public as $$
  select r.id, r.year, r.status,
         case when r.status = 'approved' then r.code_issued end,
         r.admin_note, r.created_at
  from public.activation_requests r
  where r.requester_contact = btrim(coalesce(p_contact, ''))
    and length(btrim(coalesce(p_contact, ''))) >= 3
  order by r.id desc
  limit 10;
$$;

-- 4c) Hamarino ny code: 1 code = 1 finday. Mamerina ny taona, null (tsy ekena) na -1 (efa nampiasaina tamin'ny finday hafa)
alter table public.activation_codes add column if not exists device_id text;
alter table public.activation_codes add column if not exists used_at timestamptz;
drop function if exists public.verify_activation_code(text);
create or replace function public.verify_activation_code(p_code text, p_device text default '')
returns integer
language plpgsql security definer set search_path = public as $$
declare c public.activation_codes%rowtype;
begin
  if btrim(coalesce(p_device, '')) = '' then return null; end if;
  select * into c from public.activation_codes
   where upper(code) = upper(btrim(coalesce(p_code, ''))) and active = true
   limit 1 for update;
  if not found then return null; end if;
  if c.device_id is null then
    update public.activation_codes set device_id = btrim(p_device), used_at = now() where id = c.id;
    return c.year;
  elsif c.device_id = btrim(p_device) then
    return c.year;
  end if;
  return -1;
end $$;

